function key(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function canonical(abbr: string | null, name: string | null): Entry | null {
  for (const s of [abbr, name]) {
    if (!s) continue;
    const hit = CANONICAL[key(s)];
    if (hit) return hit;
  }
  return null;
}

// Minimal correct spelling fixes only. (The old code also had a broken
// mixed-script pattern for the word "hematology" — deleted, never re-added.)
const FIXES: Array<[RegExp, string]> = [
  [/آزوفیل/g, "ائوزینوفیل"],
  [/لیمفوسیت|لمفوسیت/g, "لنفوسیت"],
  [/آلکالین\s+فسفاتاز/g, "آلکالن فسفاتاز"],
  [/آسپارتات\s+ترانسفراز/g, "آسپارتات آمینوترانسفراز"],
  [/آلانین\s+ترانسفراز/g, "آلانین آمینوترانسفراز"],
  [/هیموگلوبین/g, "هموگلوبین"],
  [/هیماتوکریت/g, "هماتوکریت"],
  [/هیولای سفید/g, "گلبول سفید"],
  [/هیولای قرمز/g, "گلبول قرمز"],
  [/بنیاد اوره/g, "نیتروژن اوره خون"],
];

export function fixSpelling(text: string): string {
  let out = text;
  for (const [pattern, replacement] of FIXES) out = out.replace(pattern, replacement);
  return out.replace(/\s{2,}/g, " ").trim();
}
