/** Normalize a name/abbr for lookup: strip every non-alphanumeric char.
 *  "W.B.C." → "wbc", "H.C.T" → "hct", "A.S.T.(SGOT)" → "astsgot". */
function key(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]/g, "");
}

const BY_KEY = new Map(Object.entries(CANONICAL).map(([k, v]) => [key(k), v]));

/** Candidate keys for a raw name/abbr: the whole string, the joined
 *  leading single letters ("W.B.C." → "wbc"), each token, and any
 *  canonical key the string starts with ("Creatinine (serum)" → "creatinine"). */
function candidates(s: string): string[] {
  const out: string[] = [];
  const full = key(s);
  if (full) out.push(full);
  const tokens = s.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);
  let lead = "";
  for (const t of tokens) {
    if (t.length === 1) lead += t;
    else break;
  }
  if (lead.length > 1) out.push(lead);
  for (const t of tokens) out.push(t);
  for (const k of BY_KEY.keys()) {
    if (full.startsWith(k) && full !== k) out.push(k);
  }
  return out;
}

/** White-cell differential counts: on most sheets they are printed
 *  with a value but genuinely no reference range, so they must not
 *  count against the ranges score. Canonical Persian names. */
export const DIFFERENTIAL_NAMES = new Set([
  "نوتروفیل",
  "لنفوسیت",
  "مونوسیت",
  "ائوزینوفیل",
  "بازوفیل",
]);

export function canonical(abbr: string | null, name: string | null): Entry | null {
  for (const s of [abbr, name]) {
    if (!s) continue;
    for (const c of candidates(s)) {
      const hit = BY_KEY.get(c);
      if (hit) return hit;
    }
    const fa = canonicalFa(s);
    if (fa) return fa;
  }
  return null;
}

/** Persian lookup: the model sometimes returns Persian names
 *  ("شمارش گلبول سفید", "اوره خون", "کراتینین سرم") instead of English
 *  abbreviations. Normalize by dropping spaces/ZWNJ and unifying ی/ک. */
function faNorm(s: string): string {
  return s.replace(/[\s\u200c\u200d]+/g, "").replace(/ي/g, "ی").replace(/ك/g, "ک");
}

// Persian spellings the model uses that differ from the canonical names.
const FA_ALIASES: Record<string, string> = {
  "هموگلوبینمتوسطگلبولقرمز": "mch",
  "پخششدگیاندازهگلبولهایقرمز": "rdw",
  "اورهخون": "bun",
};

const BY_FA = new Map<string, Entry>();
for (const [, v] of Object.entries(CANONICAL)) BY_FA.set(faNorm(v[0]), v);
for (const [alias, k] of Object.entries(FA_ALIASES)) {
  const hit = BY_KEY.get(k);
  if (hit) BY_FA.set(alias, hit);
}

function canonicalFa(s: string): Entry | null {
  const n = faNorm(s);
  if (!n) return null;
  const exact = BY_FA.get(n);
  if (exact) return exact;
  if (n.startsWith("شمارش")) {
    const rest = BY_FA.get(n.slice("شمارش".length));
    if (rest) return rest;
  }
  for (const [k, v] of BY_FA) {
    if (n.startsWith(k) && n !== k) return v;
  }
  return null;
}

// Minimal correct spelling fixes only.
const FIXES: Array<[RegExp, string]> = [
  [/آزوفیل/g, "ائوزینوفیل"],
  [/لیمفوسیت|لمفوسیت/g, "لنفوسیت"],
  [/آلکالین\s+فسفاتاز/g, "آلکالن فسفاتاز"],
  [/آسپارتات\s+ترانسفراز/g, "آسپارتات آمینوترانسفراز"],
  [/آلانین\s+ترانسفراز/g, "آلانین آمینوترانسفراز"],
  [/هیموگلوبین/g, "هموگلوبین"],
  [/هیماتوکریت/g, "هماتوکریت"],
  [/هیولای سفید/g, "گلبول سفید"],
  [/هیولای قرمز/g, "گلبول قرمز"],
  [/بنیاد اوره/g, "نیتروژن اوره خون"],
];

export function fixSpelling(text: string): string {
  let out = text;
  for (const [pattern, replacement] of FIXES) out = out.replace(pattern, replacement);
  return out.replace(/\s{2,}/g, " ").trim();
}
